#!/usr/bin/env bun

/**
 * The Commands page's list of slash commands, generated from
 * `.claude/commands/*.md`.
 *
 * Each command file starts with `# /<name> — <description>`, `<name>` being
 * the file's own name. That heading is the page's row. The rows are written to
 * `docs/js/generated/commands.ts`, which the page imports, so the page needs
 * no server; `scripts/dashboard/commands-catalog.test.ts` fails when that file
 * is not what this script writes, so a new command file cannot be left off.
 *
 * Usage: bun run dashboard:commands
 */

import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

export interface CommandEntry {
  /** The slash command, `/<file name>`. */
  name: string;
  /** The first heading's text after the em dash. */
  description: string;
}

/** The generated module, relative to the harness root. */
export const CATALOG_MODULE = "docs/js/generated/commands.ts";

const HEADING = /^#\s+(.*?)\s*$/;

export function parseCommandFile(
  file: string,
  text: string,
): { ok: true; entry: CommandEntry } | { ok: false; error: string } {
  const name = `/${file.replace(/\.md$/, "")}`;
  let heading: string | undefined;
  for (const line of text.split(/\r?\n/)) {
    const match = HEADING.exec(line);
    if (match) {
      heading = match[1];
      break;
    }
  }
  const prefix = `${name} — `;
  const description = heading?.startsWith(prefix)
    ? heading.slice(prefix.length).trim()
    : "";
  if (description) return { ok: true, entry: { name, description } };
  return {
    ok: false,
    error: `${file}: the first heading must be "# ${name} — <description>", found ${
      heading === undefined ? "none" : `"# ${heading}"`
    }`,
  };
}

/** Every `*.md` under `dir`, by command name. */
export function catalogFromDir(dir: string): {
  entries: CommandEntry[];
  errors: string[];
} {
  const entries: CommandEntry[] = [];
  const errors: string[] = [];
  for (const file of readdirSync(dir).filter((f) => f.endsWith(".md"))) {
    const parsed = parseCommandFile(
      file,
      readFileSync(join(dir, file), "utf8"),
    );
    if (parsed.ok) entries.push(parsed.entry);
    else errors.push(parsed.error);
  }
  entries.sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0));
  return { entries, errors };
}

/** The formatter's line width (biome's default). */
const LINE_WIDTH = 80;

/** One property line; past the line width the value goes on its own line, as the formatter puts it. */
function property(key: string, value: string): string {
  const literal = JSON.stringify(value);
  const line = `    ${key}: ${literal},`;
  return line.length <= LINE_WIDTH
    ? `${line}\n`
    : `    ${key}:\n      ${literal},\n`;
}

/** The generated module's text: one entry per command, formatted as the linter wants it. */
export function renderCatalogModule(entries: readonly CommandEntry[]): string {
  const rows = entries.map(
    (entry) =>
      `  {\n${property("name", entry.name)}${property("description", entry.description)}  },\n`,
  );
  return [
    "/**\n",
    " * Generated by `bun run dashboard:commands` from the first heading of each\n",
    " * `.claude/commands/*.md`. Do not edit: change the command file and run it again.\n",
    " */\n",
    "\n",
    'import type { CommandEntry } from "../../../scripts/dashboard/commands-catalog";\n',
    "\n",
    "export const COMMANDS: readonly CommandEntry[] = [\n",
    ...rows,
    "];\n",
  ].join("");
}

if (import.meta.main) {
  const root = resolve(import.meta.dir, "..", "..");
  const { entries, errors } = catalogFromDir(join(root, ".claude", "commands"));
  if (errors.length > 0) {
    console.error(
      JSON.stringify({ ok: false, data: null, error: errors.join("\n") }),
    );
    process.exit(1);
  }
  writeFileSync(join(root, CATALOG_MODULE), renderCatalogModule(entries));
  console.log(
    JSON.stringify({
      ok: true,
      data: { wrote: CATALOG_MODULE, commands: entries.length },
      error: null,
    }),
  );
}
